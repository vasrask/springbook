
CREATE TABLE reading_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_book_id BIGINT NOT NULL,

    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,

    note_type VARCHAR(30) NOT NULL DEFAULT 'GENERAL',

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reading_notes_user_book
        FOREIGN KEY (user_book_id)
        REFERENCES user_books(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_reading_notes_type
        CHECK (note_type IN (
            'GENERAL',
            'CHAPTER',
            'QUOTE',
            'REFLECTION'
        ))
);

CREATE INDEX idx_reading_notes_user_book_id
    ON reading_notes(user_book_id);
