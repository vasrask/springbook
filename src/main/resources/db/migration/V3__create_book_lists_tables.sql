
CREATE TABLE book_lists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_book_lists_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_book_lists_user_name
        UNIQUE (user_id, name)
);

CREATE INDEX idx_book_lists_user_id
    ON book_lists(user_id);


CREATE TABLE book_list_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_list_id BIGINT NOT NULL,
    user_book_id BIGINT NOT NULL,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_book_list_items_book_list
        FOREIGN KEY (book_list_id)
        REFERENCES book_lists(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_book_list_items_user_book
        FOREIGN KEY (user_book_id)
        REFERENCES user_books(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_book_list_items_list_book
        UNIQUE (book_list_id, user_book_id)
);

CREATE INDEX idx_book_list_items_book_list_id
    ON book_list_items(book_list_id);

CREATE INDEX idx_book_list_items_user_book_id
    ON book_list_items(user_book_id);
