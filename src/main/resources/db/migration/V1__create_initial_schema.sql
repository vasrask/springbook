
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn VARCHAR(20),
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    description TEXT,
    cover_url TEXT,
    genre VARCHAR(100),
    publication_year INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT chk_books_publication_year
        CHECK (publication_year IS NULL OR publication_year > 0)
);

CREATE TABLE user_books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'WANT_TO_READ',
    rating INTEGER,
    started_at DATE,
    finished_at DATE,
    personal_summary TEXT,
    personal_review TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_books_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_user_books_book
        FOREIGN KEY (book_id) REFERENCES books(id),

    CONSTRAINT uk_user_books_user_book
        UNIQUE (user_id, book_id),

    CONSTRAINT chk_user_books_status
        CHECK (status IN (
            'WANT_TO_READ',
            'CURRENTLY_READING',
            'READ',
            'ON_HOLD',
            'DROPPED'
        )),

    CONSTRAINT chk_user_books_rating
        CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),

    CONSTRAINT chk_user_books_reading_dates
        CHECK (
            started_at IS NULL
            OR finished_at IS NULL
            OR finished_at >= started_at
        )
);

CREATE INDEX idx_user_books_user_id ON user_books(user_id);
CREATE INDEX idx_user_books_book_id ON user_books(book_id);
CREATE INDEX idx_books_title ON books(title);
